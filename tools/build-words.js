// Builds words.js from tools/answers.txt (hand-picked daily answers), tools/layouts.json (their greens) and tools/allowed.txt
// (every five-letter word in the MIT-licensed `word-list` npm package, see allowed-LICENSE.txt).
// Answers are shuffled into a fixed daily order. Pass a JSON list of words to drop (e.g. from check.js).
// Usage: node tools/build-words.js [drop.json]
const fs = require('fs');
const read = f => fs.readFileSync(__dirname + '/' + f, 'utf8').split(/\s+/).filter(w => /^[a-z]{5}$/.test(w));
const drop = new Set(process.argv[2] ? JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) : []);
let answers = [...new Set(read('answers.txt'))].filter(w => !drop.has(w));
const allowed = [...new Set([...read('allowed.txt'), ...answers])].sort();
let a = 20261118; const rnd = () => (a = a * 16807 % 2147483647) / 2147483647;
for (let i = answers.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [answers[i], answers[j]] = [answers[j], answers[i]]; }
// each answer's validated green from tools/layouts.js (letters, typeface, tee, cup nook, ink dots, warp)
const layouts = fs.existsSync(__dirname + '/layouts.json') ? JSON.parse(fs.readFileSync(__dirname + '/layouts.json', 'utf8')) : {};
answers = answers.filter(w => layouts[w]);
const lay = {}; for (const w of answers) { const l = layouts[w]; lay[w] = { L: l.L, tee: l.tee, cup: l.cup, style: l.style, dots: l.dots, hills: l.hills }; }
fs.writeFileSync(__dirname + '/../words.js', '// generated by tools/build-words.js — do not edit\nwindow.TP_ANSWERS=' + JSON.stringify(answers) + ';\nwindow.TP_LAYOUTS=' + JSON.stringify(lay) + ';\nwindow.TP_ALLOWED="' + allowed.join(' ') + '";\n');
console.log('answers', answers.length, 'allowed', allowed.length, 'first days:', answers.slice(0, 5).join(' '));
